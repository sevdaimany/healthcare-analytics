USE ROLE ACCOUNTADMIN;
USE DATABASE HEALTHCARE_DB;
USE SCHEMA HEALTHCARE_DB.RAW;

-- with header row, used by gatekeeper
CREATE FILE FORMAT IF NOT EXISTS HEALTHCARE_CSV
    TYPE = 'CSV'
    FIELD_DELIMITER = ','
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    NULL_IF = ('', 'NULL')
    EMPTY_FIELD_AS_NULL = TRUE
    TRIM_SPACE = TRUE;

-- without header
CREATE FILE FORMAT IF NOT EXISTS HEALTHCARE_CSV_NOHEADER
    TYPE = 'CSV'
    FIELD_DELIMITER = ','
    SKIP_HEADER = 0
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    NULL_IF = ('', 'NULL')
    EMPTY_FIELD_AS_NULL = TRUE
    TRIM_SPACE = TRUE;

CREATE OR REPLACE STAGE GK_INCOMING
    URL = "gcs://bucket-healthcare-analytics-514911/incoming/"
    STORAGE_INTEGRATION = HEALTHCARE_GCS_INT
    FILE_FORMAT = HEALTHCARE_CSV_NOHEADER;


CREATE OR REPLACE STAGE GK_PROCESSED
    URL = "gcs://bucket-healthcare-analytics-514911/processed/"
    STORAGE_INTEGRATION = HEALTHCARE_GCS_INT
    FILE_FORMAT = HEALTHCARE_CSV_NOHEADER;

CREATE OR REPLACE STAGE GK_QUARANTINE
    URL = "gcs://bucket-healthcare-analytics-514911/quarantine/"
    STORAGE_INTEGRATION = HEALTHCARE_GCS_INT
    FILE_FORMAT = HEALTHCARE_CSV_NOHEADER;
    
GRANT USAGE ON STAGE GK_PROCESSED TO ROLE HEALTHCARE_ROLE;
GRANT USAGE ON STAGE GK_PROCESSED TO ROLE HEALTHCARE_ROLE;
GRANT USAGE ON STAGE GK_QUARANTINE TO ROLE HEALTHCARE_ROLE;

SHOW GRANTS TO ROLE HEALTHCARE_ROLE;

USE ROLE HEALTHCARE_ROLE;
LIST @HEALTHCARE_DB.RAW.GK_INCOMING;
